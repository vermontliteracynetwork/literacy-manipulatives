#!/usr/bin/env python3
"""Imports her Symbolic Grammar "All Formulas" PDF (the master list: every sentence formula by unit, with its skill,
shorthand name, model sentence, required words, formula, formula code and purpose) into src/lib/writer/masterList.ts.

Usage: python3 -I scripts/import-master-list.py "Symbolic_Grammar_All_Formulas.pdf"
Needs pdfplumber (pip install pdfplumber). Edit the PDF and rerun, never the output.
Levels are not in this PDF: each row keeps the levels it had in the earlier list (same code and sentence, else same
code), and a new formula is listed for Levels A, B and C.
"""
import json
import os
import re
import sys

import pdfplumber

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
clean = lambda c: re.sub(r'\s+', ' ', c or '').strip().replace('– ', '–')

rows = []
with pdfplumber.open(sys.argv[1]) as pdf:
    for page in pdf.pages:
        for table in page.extract_tables():
            for r in table:
                cells = [clean(c) for c in r]
                if len(cells) != 8 or cells[0] in ('', 'Unit') or not re.match(r'^\d+ ', cells[0]):
                    continue
                unit, skill, name, sentence, required, formula, code, purpose = cells
                rows.append({'unit': unit, 'skill': skill, 'name': name, 'sentence': sentence, 'required': required,
                             'formula': formula, 'code': code, 'purpose': purpose})

# Levels from the earlier list.
old_path = os.path.join(ROOT, 'node_modules', 'symbolic-grammar-engine', 'src', 'writer', 'formulaList.ts')
old = []
for line in open(old_path, encoding='utf8'):
    line = line.strip().rstrip(',')
    if line.startswith('{"code"'):
        old.append(json.loads(line))
for r in rows:
    hit = next((o for o in old if o['code'].rstrip('*') == r['code'] and o['example'] == r['sentence']), None) \
        or next((o for o in old if o['code'].rstrip('*') == r['code']), None)
    r['levels'] = hit['levels'] if hit else ['A', 'B', 'C']

out = ['// Her Symbolic Grammar master list, "All Formulas" (2026-11-17): every sentence formula by unit, with its skill,',
       '// shorthand name, model sentence, required words, formula (the symbols, in order), formula code and purpose.',
       '// Generated by scripts/import-master-list.py from her PDF; edit there, not here. This is the one formula list',
       '// every Symbolic Grammar and Literacy Manipulatives program reads.',
       'export interface MasterFormula { unit: string; skill: string; name: string; sentence: string; required: string; formula: string; code: string; purpose: string; levels: string[] }',
       '',
       'export const MASTER_FORMULAS: MasterFormula[] = [']
for r in rows:
    out.append('  ' + json.dumps({k: r[k] for k in ('unit', 'skill', 'name', 'sentence', 'required', 'formula', 'code', 'purpose', 'levels')}, ensure_ascii=False) + ',')
out.append('];')
open(os.path.join(ROOT, 'src', 'lib', 'writer', 'masterList.ts'), 'w', encoding='utf8').write('\n'.join(out) + '\n')
print(len(rows), 'formulas written to src/lib/writer/masterList.ts')
