#!/usr/bin/env python3
"""Imports her "All Sentence Formulas" PDF (121 formulas in teaching order) into src/lib/writer/formulaList.ts.

Usage: pdftotext -layout "Symbolic_Grammar_All_Sentence_Formulas.pdf" formulas.txt
       python3 -I scripts/import-formula-list.py formulas.txt
Each row: code, levels, formula breakdown, example sentence, required words. Edit the PDF and rerun, not the output.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
text = open(sys.argv[1], encoding='utf8').read()
rows = []
for page in text.split('\f'):
    lines = page.split('\n')
    head = next((l for l in lines if 'Formula breakdown' in l and 'Example sentence' in l), None)
    if not head:
        continue
    b, e, r = head.index('Formula breakdown'), head.index('Example sentence'), head.index('Required words')
    body = lines[lines.index(head) + 1:]
    groups, cur = [], []
    for l in body:
        if not l.strip() or l.strip().startswith('Symbolic Grammar ·'):
            if cur:
                groups.append(cur)
            cur = []
        else:
            cur.append(l)
    if cur:
        groups.append(cur)
    for g in groups:
        lv = next((l for l in g if l.strip().startswith('Levels')), None)
        if not lv:
            continue
        cell = lambda a, z: re.sub(r'\s+', ' ', ' '.join(l[a:z] if z else l[a:] for l in g)).strip()
        code_lines = [l[:b].strip() for l in g if l[:b].strip() and not l.strip().startswith('Levels') and l.index(l.strip()[0]) < 8]
        code = code_lines[0].split()[0] if code_lines else ''
        # A code cut off at the end of its column ("(S3.P.B)C[S2.A.P.V"): close its brackets.
        code += ']' * (code.count('[') - code.count(']')) + ')' * (code.count('(') - code.count(')'))
        levels = re.findall(r'\b[ABC]\b', lv[:b])
        rows.append({
            'code': code, 'levels': levels,
            'breakdown': cell(b, e), 'example': cell(e, r), 'required': cell(r, None),
        })
out = os.path.join(ROOT, 'src', 'lib', 'writer', 'formulaList.ts')
with open(out, 'w', encoding='utf8') as f:
    f.write('// Her "All Sentence Formulas" list (2026-11-12): every current formula in teaching order, with its levels,\n')
    f.write('// formula breakdown, example sentence and required words. Generated by scripts/import-formula-list.py from\n')
    f.write('// her PDF; edit there, not here. A code marked * in her list (S1.PN.R) is a working code.\n')
    f.write('export interface ListedFormula { code: string; levels: string[]; breakdown: string; example: string; required: string }\n\n')
    f.write('export const FORMULA_LIST: ListedFormula[] = [\n')
    for x in rows:
        f.write('  ' + json.dumps(x, ensure_ascii=False) + ',\n')
    f.write('];\n')
# The formula cards (src/lib/writer/formulas.ts) take her current code where the card's model sentence is in the list.
cards = os.path.join(ROOT, 'src', 'lib', 'writer', 'formulas.ts')
src = open(cards, encoding='utf8').read()
by_example = {x['example']: x['code'].rstrip('*') for x in rows}
def recode(m):
    rec = json.loads(m.group(1))
    if rec['sentence'] in by_example:
        rec['code'] = by_example[rec['sentence']]
    return '  ' + json.dumps(rec, ensure_ascii=False) + ','
src = re.sub(r'^  (\{"unit".*\}),$', recode, src, flags=re.M)
open(cards, 'w', encoding='utf8').write(src)
print(len(rows), 'formulas')
for x in rows[:6] + rows[-4:]:
    print(x)
